#!/usr/bin/env python3
"""Check the integrity of internal link, image and anchor references in the repository's Markdown documents.

Walks every tracked `.md` document and verifies two things.

1. Relative-path links pointing at other files in the repository (`[text](path)`) and image
   references (`![alt](path)`, `<img src="path">`) point at files that actually exist.
2. Document anchor links (`[text](#heading)`, `[text](other.md#heading)`) point at headings
   that actually exist in the target `.md` document. Anchor slugs are generated by
   reproducing GitHub's rules with the standard library (lowercase → remove everything
   except `\\p{Word}`, hyphens and spaces → spaces to hyphens, and when the same slug
   repeats, a `-1`, `-2` suffix in order of appearance).

If there is even one broken reference it exits with code 1, so it can be used as is for
the CI merge gate (`.github/workflows/docs.yml`) and for contributors' local checks.

Not checked:
- External URLs (`http://`, `https://`, `mailto:`, `tel:`, `data:`): they depend on the
  network and are flaky, so this deterministic gate does not handle them. External link
  status is checked separately.
- The fragment after `#` in links pointing at non-`.md` files (e.g. a source code line
  number): it is not a heading anchor, so only the file's existence is checked, not the anchor.
- The `#` fragment of image references: heading anchors are meaningless for images.
- Example links and heading-like comments inside fenced code blocks (blocks wrapped in ``` or ~~~):
  they are code examples, not real references or headings, so they are skipped.

Uses only the standard library and makes no network connections. Run: `python3 -I scripts/check-doc-links.py`
"""
import os
import re
import subprocess
import sys
import unicodedata
from collections import defaultdict

# Links of the form [text](path) that are not images (`![...]`). The path runs up to the first whitespace (excluding a "..." title).
MD_LINK = re.compile(r"(?<!\!)\[[^\]]*\]\(([^)\s]+)")
# ![alt](path) image links.
MD_IMAGE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)")
# <img ... src="path" ...> HTML images.
HTML_IMAGE = re.compile(r"<img[^>]*\bsrc=[\"']([^\"']+)[\"']", re.IGNORECASE)

# Network/non-file schemes. Anchors (`#`) refer to the same document, so they are not listed here.
EXTERNAL_PREFIXES = ("http://", "https://", "mailto:", "tel:", "data:")

ATX_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
# Strips inline Markdown from heading text, leaving only plain text.
MD_INLINE_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def is_external(target: str) -> bool:
    return target.startswith(EXTERNAL_PREFIXES)


def _is_word_char(ch: str) -> bool:
    """Decide whether a character is a `\\p{Word}` character kept by GitHub's anchor slug rules.

    Ruby regex `\\p{Word}` = Letter(L*) + Mark(M*) + Decimal_Number(Nd)
    + Connector_Punctuation(Pc) + Join_Control(U+200C, U+200D). Hangul, Han characters,
    underscores, emoji variation selectors (Mn), etc. are kept as is.
    """
    if ch == "_":
        return True
    if ch in ("‌", "‍"):
        return True
    category = unicodedata.category(ch)
    if category[0] in ("L", "M"):
        return True
    return category in ("Nd", "Pc")


def slugify(text: str) -> str:
    """Convert heading text to a GitHub anchor slug (excluding duplicate-suffix handling)."""
    text = text.strip().lower()
    out = []
    for ch in text:
        if ch == " ":
            out.append("-")
        elif ch == "-" or _is_word_char(ch):
            out.append(ch)
    return "".join(out)


def heading_slugs(root: str, md: str) -> set:
    """Build the set of GitHub anchor slugs from all ATX headings in the file.

    When the same slug repeats, a `-1`, `-2` suffix is appended in order of appearance, as GitHub does.
    """
    slugs = set()
    counts = defaultdict(int)
    in_fence = False
    with open(os.path.join(root, md), encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            stripped = line.lstrip()
            if stripped.startswith("```") or stripped.startswith("~~~"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            match = ATX_HEADING.match(line.rstrip("\n"))
            if not match:
                continue
            raw = match.group(2)
            raw = MD_INLINE_LINK.sub(r"\1", raw)
            raw = raw.replace("`", "").replace("*", "").replace("_", "")
            base = slugify(raw)
            seen = counts[base]
            counts[base] += 1
            slugs.add(base if seen == 0 else f"{base}-{seen}")
    return slugs


def main() -> int:
    root = subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True
    ).strip()
    tracked = subprocess.check_output(
        ["git", "ls-files"], cwd=root, text=True
    ).splitlines()
    md_files = [f for f in tracked if f.endswith(".md")]

    slug_cache: dict = {}

    def slugs_of(md_path: str) -> set:
        if md_path not in slug_cache:
            slug_cache[md_path] = heading_slugs(root, md_path)
        return slug_cache[md_path]

    checked_files = 0
    checked_anchors = 0
    broken_files = []
    broken_anchors = []
    for md in md_files:
        with open(os.path.join(root, md), encoding="utf-8", errors="ignore") as fh:
            lines = fh.readlines()
        base_dir = os.path.dirname(md)
        in_fence = False
        for lineno, line in enumerate(lines, 1):
            stripped = line.lstrip()
            if stripped.startswith("```") or stripped.startswith("~~~"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            for pattern in (MD_LINK, MD_IMAGE, HTML_IMAGE):
                for match in pattern.finditer(line):
                    target = match.group(1).strip()
                    if is_external(target):
                        continue

                    if target.startswith("#"):
                        file_part, anchor = "", target[1:]
                    elif "#" in target:
                        file_part, anchor = target.split("#", 1)
                    else:
                        file_part, anchor = target, ""
                    file_part = file_part.split("?", 1)[0]
                    anchor = anchor.strip()

                    # The .md document being pointed at (the anchor-check target). For a link to another
                    # file, that file; for a `#anchor` with no file part, the document itself.
                    target_md = None
                    if file_part:
                        checked_files += 1
                        resolved = os.path.normpath(
                            os.path.join(root, base_dir, file_part)
                        )
                        if not os.path.exists(resolved):
                            broken_files.append((md, lineno, target))
                            continue
                        if file_part.endswith(".md"):
                            target_md = os.path.normpath(
                                os.path.join(base_dir, file_part)
                            )
                    else:
                        target_md = md

                    # Anchors are meaningful only for body links (MD_LINK). The `#` fragment of
                    # image references is skipped.
                    if anchor and target_md is not None and pattern is MD_LINK:
                        checked_anchors += 1
                        if anchor not in slugs_of(target_md):
                            broken_anchors.append((md, lineno, target, target_md))

    print(
        f"추적 마크다운 {len(md_files)}개 · 파일 참조 {checked_files}개 · "
        f"앵커 참조 {checked_anchors}개 검사"
    )
    if broken_files:
        print(f"깨진 파일 참조 {len(broken_files)}개 — 가리키는 파일이 저장소에 없습니다:")
        for md, lineno, target in broken_files:
            print(f"  {md}:{lineno} -> {target}")
    if broken_anchors:
        print(f"깨진 앵커 참조 {len(broken_anchors)}개 — 대상 문서에 그 헤딩이 없습니다:")
        for md, lineno, target, target_md in broken_anchors:
            print(f"  {md}:{lineno} -> {target}  (대상: {target_md})")
    if broken_files or broken_anchors:
        return 1
    print("깨진 참조 0 — 모든 내부 링크·이미지·앵커가 실존 대상을 가리킵니다.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
