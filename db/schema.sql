CREATE TABLE IF NOT EXISTS llm_profiles (
    id               BIGSERIAL PRIMARY KEY,
    name             TEXT NOT NULL UNIQUE,
    format           TEXT NOT NULL CHECK (format IN ('openai','anthropic','openai-responses','ollama')),
    base_url         TEXT,
    proxy            TEXT,
    model            TEXT NOT NULL,
    api_key          TEXT,
    api_key_hint     TEXT,
    rate_per_second  DOUBLE PRECISION NOT NULL DEFAULT 0,
    rate_per_minute  DOUBLE PRECISION NOT NULL DEFAULT 0,
    context_window_k INTEGER NOT NULL DEFAULT 0,
    -- Independent reasoning fields: thinking_type controls enablement (''/disabled/enabled);
    -- reasoning_effort controls intensity (''/low/medium/high/xhigh/max), without coupling them.
    reasoning_effort TEXT NOT NULL DEFAULT '',
    thinking_type    TEXT NOT NULL DEFAULT '',
    is_default       BOOLEAN NOT NULL DEFAULT false,
    -- Pool failover parameters; see the LLM pool design:
    --   priority: higher values are selected first; the active profile (is_default) always leads regardless of priority.
    --   pool_exclude: true excludes automatic failover, but explicit agent/task binding remains allowed.
    priority         INTEGER NOT NULL DEFAULT 0,
    pool_exclude     BOOLEAN NOT NULL DEFAULT false,
    -- streaming=true (default) uses SSE; false uses real nonstreaming (stream:false, one JSON response).
    streaming        BOOLEAN NOT NULL DEFAULT true,
    -- Output token cap per response. 0 omits the field and uses server defaults, preserving prior behavior.
    -- Unlike context_window_k (total capacity used locally for compaction), this value is sent with requests.
    max_tokens       INTEGER NOT NULL DEFAULT 0,
    -- Request field name for the output cap; applies only to format='openai':
    --   '': max_tokens (default, compatible with most gateways).
    --   'max_completion_tokens': newer field required by OpenAI reasoning models (o-series/GPT-5);
    --                            sending max_tokens produces unsupported_parameter.
    -- Anthropic (required max_tokens) and openai-responses (max_output_tokens) use their own field names.
    max_tokens_field TEXT NOT NULL DEFAULT '',
    -- Custom session header: when nonempty, send this HTTP header with the current run's session ID
    -- (chat conversation/worker intent), for gateway prompt caching or sticky routing. Empty omits it.
    session_header_key TEXT NOT NULL DEFAULT '',
    -- Retry overrides: attempts 0=global default/-1=disabled/>0=explicit; interval 0=default backoff/>0=fixed milliseconds.
    -- The groups cover connection, empty-response, and same-provider safety-window retries; see ALTER comments below.
    retry_connect_attempts    INTEGER NOT NULL DEFAULT 0,
    retry_connect_interval_ms INTEGER NOT NULL DEFAULT 0,
    retry_empty_attempts      INTEGER NOT NULL DEFAULT 0,
    retry_empty_interval_ms   INTEGER NOT NULL DEFAULT 0,
    retry_stream_attempts     INTEGER NOT NULL DEFAULT 0,
    retry_stream_interval_ms  INTEGER NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
