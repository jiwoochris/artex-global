-- =====================================================================
-- M. Finding IM notifications.
--
-- Three tables deliberately isolate failures: the finding transaction (RecordFindingTx, holding
-- a task-row lock) performs only a blind INSERT, without reading channels or evaluating user filters.
-- Otherwise a malformed webhook filter could contaminate/abort the transaction and prevent saving findings.
--
--   notification_channels: mutable channel configuration, credentials, and UI management.
--   notification_events: event facts, blind-inserted within the finding transaction, including rendering snapshots.
--   notification_deliveries: delivery jobs from later fan-out, with state/retries/batches.
-- =====================================================================

-- Channel instances: any number per kind, such as separate DingTalk bots for emergency and daily groups.
-- Server allowlists validate kind without a CHECK, like findings.status,
-- so adding a channel type requires no schema change.
CREATE TABLE IF NOT EXISTS notification_channels (
    id           BIGSERIAL PRIMARY KEY,
    name         TEXT NOT NULL,
    -- Kinds: dingtalk / feishu / wecom / webhook / telegram / email.
    kind         TEXT NOT NULL,
    enabled      BOOLEAN NOT NULL DEFAULT true,
    -- Credentials are stored in plaintext and masked in UI responses (server maskChannelSecrets). Channel fields vary widely;
    -- JSONB plus strict per-kind Go validation avoids many nullable per-channel columns.
    --   dingtalk {webhook,secret}
    --   feishu   {webhook,secret}
    --   wecom    {webhook}
    --   webhook  {url,method,content_type,headers{},body_template}
    --   telegram {bot_token,chat_id,base_url}
    --   email    {host,port,username,password,from,to[],tls}
    config       JSONB NOT NULL DEFAULT '{}',
    -- Timing: realtime sends on match; digest batches findings into one message per global period.
    mode         TEXT NOT NULL DEFAULT 'realtime',
    -- Optional filters; omitted fields do not filter:
    --   min_severity       ''|low|medium|high|critical
    --   task_ids/asset_ids: empty arrays mean unrestricted; otherwise require a nonempty intersection.
    --   vulnclass_include/exclude: case-insensitive substring keywords; empty include accepts all.
    --   on_status_change: bool, meaningful only for realtime mode.
    filter       JSONB NOT NULL DEFAULT '{}',
    -- Maximum deliveries per minute; 0 means unlimited. Default 20 matches DingTalk/WeCom published limits.
    -- Excess deliveries wait until a later tick rather than being dropped.
    rate_per_min INTEGER NOT NULL DEFAULT 20,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
DROP TRIGGER IF EXISTS trg_notification_channels_upd ON notification_channels;
CREATE TRIGGER trg_notification_channels_upd BEFORE UPDATE ON notification_channels
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Event facts are written in the same transaction as RecordFindingTx/status changes, making finding persistence
-- and notification enqueueing atomic, without a successful-commit/missing-queue window that loses messages.
-- Snapshots are intentionally redundant: later edits to finding names, severity, or status must not change
-- the event-time notification, and fan-out/rendering need not query findings/tasks/assets again.
-- Finding deletion does not cascade to events, matching findings surviving task deletion independently.
CREATE TABLE IF NOT EXISTS notification_events (
    id         BIGSERIAL PRIMARY KEY,
    -- finding_created | finding_status_changed
    kind       TEXT NOT NULL,
    finding_id BIGINT NOT NULL,
    snapshot   JSONB NOT NULL,
    -- Idempotent fan-out marker: dispatchers select pending events by this column and set true after processing.
    -- Retain rows rather than deleting them so delivery history can trace back to events.
    fanned_out BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notification_events_pending
    ON notification_events(id) WHERE NOT fanned_out;

-- Delivery jobs: one event x one enabled channel per row. Fan-out occurs after the source transaction,
-- so later-enabled channels do not replay history, matching late agent_triggers behavior
-- and preventing a burst of historical backlog when enabling a channel.
-- channel_id cascades deletion because delivery history has no meaning without channel configuration.
CREATE TABLE IF NOT EXISTS notification_deliveries (
    id          BIGSERIAL PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES notification_events(id) ON DELETE CASCADE,
    channel_id  BIGINT NOT NULL REFERENCES notification_channels(id) ON DELETE CASCADE,
    -- pending / sent / failed (retries exhausted, manual retry allowed) / skipped (disabled channel or canceled batch).
    -- pending / sending (claimed with an unexpired dispatcher lease) / sent /
    -- failed (exhausted retries or permanent failure; manual retry allowed) / skipped (disabled channel). No CHECK;
    -- server allowlists validate values, like findings.status.
    state       TEXT NOT NULL DEFAULT 'pending',
    attempts    INTEGER NOT NULL DEFAULT 0,
    -- Both next claim time and lease expiry: moving it into the future on claim establishes a lease,
    -- so unexpired leases and future retries share one condition without an additional
    -- lease_until column. Sending rows left by a crash become reclaimable after lease expiry.
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error  TEXT NOT NULL DEFAULT '',
    -- Shared within a digest batch; always NULL for realtime. Render the batch as one message and mark all sent together.
    batch_id    BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at     TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_due
    ON notification_deliveries(next_attempt_at) WHERE state='pending';
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_history
    ON notification_deliveries(id DESC);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_batch
    ON notification_deliveries(batch_id) WHERE batch_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_channel
    ON notification_deliveries(channel_id, id DESC);

