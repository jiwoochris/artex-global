-- =====================================================================
-- 0. Common: updated_at trigger.
-- =====================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

-- Safe text-to-inet conversion: invalid input returns NULL instead of 22P02. assets.ip is free text;
-- agents and asset APIs may store hostnames. A direct a.ip::inet cast would let one bad row
-- break company-ownership recalculation. Callers use try_inet(...) IS NULL to find and report such rows.
-- Avoid pg_input_is_valid because it requires PG16+; existing older databases remain supported.
CREATE OR REPLACE FUNCTION try_inet(value text) RETURNS inet AS $$
BEGIN
    RETURN value::inet;
EXCEPTION WHEN others THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE STRICT;

