-- schema.sql runs every startup, so backfill only when the column does not yet exist;
-- otherwise restarts would overwrite users' later combinations. Legacy reasoning_effort mapping:
--   'off': explicitly disabled -> thinking_type='disabled', clear intensity.
--   'low/medium/high/max': enabled plus intensity -> thinking_type='enabled', preserve intensity.
--   '': omit both fields (default).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'llm_profiles' AND column_name = 'thinking_type'
    ) THEN
        ALTER TABLE llm_profiles ADD COLUMN thinking_type TEXT NOT NULL DEFAULT '';
        UPDATE llm_profiles SET thinking_type = 'enabled'
            WHERE reasoning_effort IN ('low','medium','high','max');
        UPDATE llm_profiles SET thinking_type = 'disabled', reasoning_effort = ''
            WHERE reasoning_effort = 'off';
    END IF;
END $$;

-- LLM pool circuit-breaker state: consecutive failures (balance/key/rate limit) put a profile into cooldown,
-- and failover skips it. Memory is authoritative; persistence preserves cooldown across restarts. Load only
-- unexpired rows (open_until > now); expired rows naturally become normal pending the next half-open probe.
CREATE TABLE IF NOT EXISTS llm_profile_health (
    profile_id  BIGINT PRIMARY KEY REFERENCES llm_profiles(id) ON DELETE CASCADE,
    fails       INTEGER NOT NULL DEFAULT 0,  -- Current consecutive failures; reset on success.
    trips       INTEGER NOT NULL DEFAULT 0,  -- Cumulative trips for exponential cooldown backoff.
    open_until  TIMESTAMPTZ,                 -- Cooldown expiry; NULL/expired means closed.
    last_error  TEXT NOT NULL DEFAULT '',
    last_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

